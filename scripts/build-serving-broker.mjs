import { build } from "esbuild";
import { mkdir, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import { format, resolveConfig } from "prettier";

const root = fileURLToPath(new URL("../", import.meta.url));
const result = await build({
  absWorkingDir: root,
  entryPoints: ["packages/serving/src/broker.ts"],
  bundle: true,
  write: false,
  format: "iife",
  platform: "browser",
  target: ["chrome120", "firefox120"],
  conditions: ["development"],
  minify: true,
  legalComments: "none",
  metafile: true,
  plugins: [
    {
      name: "discard-unused-server-exports",
      setup(build) {
        // Shared schema barrels re-export server helpers. Only unused Node imports may disappear;
        // a retained Node dependency fails below rather than becoming a browser polyfill.
        build.onResolve({ filter: /^node:/ }, ({ path }) => ({
          path,
          external: true,
          sideEffects: false
        }));
      }
    }
  ]
});
for (const output of Object.values(result.metafile.outputs)) {
  if (output.imports.length !== 0)
    throw new Error(
      `The browser broker retains external imports: ${output.imports.map(({ path }) => path).join(", ")}`
    );
}
const directory = new URL("../packages/serving/src/generated/", import.meta.url);
await mkdir(directory, { recursive: true });
const target = fileURLToPath(new URL("broker-script.ts", directory));
await writeFile(
  target,
  await format(
    `// Generated by scripts/build-serving-broker.mjs; do not edit.\nexport const brokerScript: string = ${JSON.stringify(result.outputFiles[0].text)};\n`,
    { ...(await resolveConfig(target)), filepath: target }
  )
);
