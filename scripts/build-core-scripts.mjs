import { build } from "esbuild";
import { createHash } from "node:crypto";
import { mkdir, readFile, rename, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";

/**
 * Bundles core's browser scripts into `packages/core/src/generated/`, gitignored and kept from the
 * formatter, one module of string constants each. Core's build and test, root `prepare` and
 * `typecheck`, every vitest run and `pnpm dev` run it.
 *
 * An inline script goes into pages as `<script>text</script>`, so pages allow it by the hash of
 * that exact text; its module exports both from one build.
 */
const inline = (name) => (text) => {
  // Each would end or re-enter the script element early in the HTML parser.
  if (/<\/?script|<!--/i.test(text)) throw new Error(`${name} can't be inlined as built.`);
  const hash = createHash("sha256").update(text).digest("base64");
  return `export const ${name}: string = ${JSON.stringify(text)};
/** The CSP source that allows exactly that text: its UTF-8 bytes' SHA-256, in base64. */
export const ${name}Hash: string = ${JSON.stringify(`'sha256-${hash}'`)};
`;
};

const outputs = [
  {
    entry: "packages/core/src/switcher/relay.ts",
    file: "relay-script.ts",
    render: inline("relayScript")
  }
];

const root = fileURLToPath(new URL("../", import.meta.url));
const directory = new URL("../packages/core/src/generated/", import.meta.url);
await mkdir(directory, { recursive: true });
for (const { entry, file, render } of outputs) {
  const result = await build({
    absWorkingDir: root,
    entryPoints: [entry],
    bundle: true,
    write: false,
    format: "iife",
    platform: "browser",
    target: ["chrome120", "firefox120", "safari16"],
    minify: true,
    legalComments: "none",
    metafile: true
  });
  for (const output of Object.values(result.metafile.outputs))
    if (output.imports.length !== 0)
      throw new Error(
        `${entry} retains external imports: ${output.imports.map(({ path }) => path)}`
      );
  const contents = `// Generated by scripts/build-core-scripts.mjs from ${entry}; do not edit.
${render(result.outputFiles[0].text.trim())}`;
  const target = fileURLToPath(new URL(file, directory));
  // Unchanged output stays untouched, and a change lands whole, for a typecheck reading it meanwhile.
  if ((await readFile(target, "utf8").catch(() => undefined)) === contents) continue;
  await writeFile(`${target}.tmp`, contents);
  await rename(`${target}.tmp`, target);
}
