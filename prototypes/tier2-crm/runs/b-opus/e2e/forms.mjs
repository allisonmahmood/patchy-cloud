import { chromium } from "/home/quan2m/.local/share/mise/installs/npm-playwright/1.63.0/node_modules/playwright/index.mjs";
const browser = await chromium.launch({ executablePath: "/usr/bin/chromium" });
const page = await browser.newPage({ viewport: { width: 1400, height: 900 } });
page.on("console", (m) => m.type() === "error" && console.log("console:", m.text()));
await page.goto(process.argv[2]);
await page.waitForTimeout(2500);
const f = page.frames().find((x) => x.url().includes("/~content/"));
await f.click("text=Companies");
await f.click("text=New company");
await f.fill('dialog input[name="name"]', "Kestrel Labs");
await f.press('dialog input[name="name"]', "Enter");
await f.waitForSelector("h1:has-text('Kestrel Labs')");
console.log("company created via form");
await f.click("button:has-text('New deal')");
await f.fill('dialog input[name="title"]', "Kestrel pilot");
await f.fill('dialog input[name="value"]', "8000");
await f.check('dialog input[name="private"]');
await page.screenshot({ path: "e2e/newdeal.png" });
await f.click("dialog >> text=Create deal");
await f.waitForSelector("text=Kestrel pilot");
console.log("deal created via form");
await f.click("text=New contact");
await f.fill('dialog input[name="firstName"]', "Ana");
await f.fill('dialog input[name="email"]', "wen.mensah@acmerobotics.example");
await f.click("dialog >> text=Create contact");
await f.waitForSelector("dialog .alert");
console.log("dup contact:", await f.textContent("dialog .alert"));
await f.fill('dialog input[name="email"]', "ana@kestrel.example");
await f.click("dialog >> text=Create contact");
await f.waitForSelector("td:has-text('ana@kestrel.example')");
console.log("contact created");
await f.click("nav >> text=Contacts");
await f.waitForSelector("text=Load more");
await page.screenshot({ path: "e2e/contacts.png" });
await f.click("text=Load more");
await page.waitForTimeout(800);
console.log("rows after load more:", await f.$$eval("tbody tr", (r) => r.length));
await browser.close();
